-- V4: MENSAJES DEL FORMULARIO DE CONTACTO (HB-21, ADR proposed 20261110)
-- ============================================================================

-- numero: el que ve quien escribe ("Su número es 4821").
-- clave_envio: la genera el formulario; un reenvío con la misma clave no crea otro mensaje.
-- ip_origen: solo para el límite por IP.
CREATE TABLE mensaje_contacto (
    numero BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave_envio UUID NOT NULL,
    tema VARCHAR(20) NOT NULL,
    texto TEXT NOT NULL,
    codigo_error VARCHAR(64) NULL,
    correo VARCHAR(254) NOT NULL,
    ip_origen VARCHAR(45) NULL,
    estado VARCHAR(20) NOT NULL,
    recibido_en TIMESTAMP NOT NULL,
    respuesta TEXT NULL,
    respondido_en TIMESTAMP NULL,
    CONSTRAINT uk_mensaje_contacto_clave_envio UNIQUE (clave_envio)
);

-- Los dos límites cuentan mensajes recientes por correo y por IP.
CREATE INDEX idx_mensaje_contacto_correo_recibido ON mensaje_contacto (correo, recibido_en);
CREATE INDEX idx_mensaje_contacto_ip_recibido ON mensaje_contacto (ip_origen, recibido_en);
CREATE INDEX idx_mensaje_contacto_estado ON mensaje_contacto (estado);
